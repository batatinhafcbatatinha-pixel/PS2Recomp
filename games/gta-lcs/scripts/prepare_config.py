"""Write config/recomp.toml for the game executable (SLUS_214.23) from the Ghidra export."""
import csv
import json
import tomllib

from local_tools import ROOT

config = ROOT / 'config'
ghidra = tomllib.loads((config / 'ghidra.toml').read_text())['general']
rows = list(csv.DictReader((config / 'ghidra-functions-only.csv').open()))
if not rows:
    raise SystemExit('Empty Ghidra function map; run ghidra-export.cmd first')
# Ghidra's End is the highest address of the body; a body with a far-away piece (a branch into shared code) then
# spans megabytes of other functions (FUN_001f3398: 36 bytes, End +3 MB). Cap every end at the next function start;
# branches past it go through the function table like any other cross-function jump.
rows.sort(key=lambda r: int(r['Start'], 16))
capped = 0
with (config / 'ghidra-functions-capped.csv').open('w', newline='') as out:
    writer = csv.writer(out)
    writer.writerow(['Name', 'Start', 'End', 'Size'])
    for i, r in enumerate(rows):
        start, end = int(r['Start'], 16), int(r['End'], 16)
        if i + 1 < len(rows) and end > int(rows[i + 1]['Start'], 16):
            end = int(rows[i + 1]['Start'], 16)
            capped += 1
        writer.writerow([r['Name'], f'0x{start:08X}', f'0x{end:08X}', end - start])
q = json.dumps  # paths relative to the repository root, where the tool runs
lines = ['# Generated by scripts/prepare_config.py from config/ghidra.toml; do not edit.', '[general]',
         f'input = {q("game_files/SLUS_214.23")}',
         f'output = {q("project/runner")}',
         f'ghidra_output = {q("config/ghidra-functions-capped.csv")}',
         'single_file_output = false', 'low_memory_mode = true', 'output_worker_threads = 1',
         'patch_syscalls = false', 'patch_cop0 = true', 'patch_cache = true', 'stubs = [']
lines += [f'  {q(s)},' for s in ghidra.get('stubs', [])]
lines += [']', 'skip = []']
(config / 'recomp.toml').write_text('\n'.join(lines) + '\n')
print(f'{len(rows)} functions ({capped} ends capped at the next start); {len(ghidra.get("stubs", []))} kernel syscall wrappers bound to the runtime')
