"""Translate and compile one guest function while the game runs (called by the runtime, see ps2_hot.cpp).

usage: hotrecomp.py <port>/observed/hot <hex address>_<hex hash>
Input: ram_<tag>.bin (the 32 MB of guest RAM at that moment). Output: hot_<tag>.dll (or .so) exporting
ps2x_hot_bind/ps2x_hot_entry, and hot_<addr>.log. The function is translated by ps2_recomp from the RAM image;
calls to other functions go through the runtime's table; the PS2Runtime services it uses are forwarded through the
table the runtime passes in (runtime/ps2_hot_api.h). Compile flags are those of the game's own generated code
(read from build/native/build.ninja), so the code is exactly what a full build would produce.
"""
import os
import re
import shlex
import shutil
import struct
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
RAM_SIZE = 32 * 1024 * 1024

SHIM = r'''// Generated by tools/ps2port/hotrecomp.py: PS2Runtime services forwarded to the executable's table.
#include "runtime/ps2_hot_api.h"
static const PS2HotApi* g_api = nullptr;
uint8_t PS2Runtime::Load8(uint8_t* r, R5900Context* c, uint32_t a) { return (this->*g_api->load8)(r, c, a); }
uint16_t PS2Runtime::Load16(uint8_t* r, R5900Context* c, uint32_t a) { return (this->*g_api->load16)(r, c, a); }
uint32_t PS2Runtime::Load32(uint8_t* r, R5900Context* c, uint32_t a) { return (this->*g_api->load32)(r, c, a); }
uint64_t PS2Runtime::Load64(uint8_t* r, R5900Context* c, uint32_t a) { return (this->*g_api->load64)(r, c, a); }
__m128i PS2Runtime::Load128(uint8_t* r, R5900Context* c, uint32_t a) { return (this->*g_api->load128)(r, c, a); }
void PS2Runtime::Store8(uint8_t* r, R5900Context* c, uint32_t a, uint8_t v) { (this->*g_api->store8)(r, c, a, v); }
void PS2Runtime::Store16(uint8_t* r, R5900Context* c, uint32_t a, uint16_t v) { (this->*g_api->store16)(r, c, a, v); }
void PS2Runtime::Store32(uint8_t* r, R5900Context* c, uint32_t a, uint32_t v) { (this->*g_api->store32)(r, c, a, v); }
void PS2Runtime::Store64(uint8_t* r, R5900Context* c, uint32_t a, uint64_t v) { (this->*g_api->store64)(r, c, a, v); }
void PS2Runtime::Store128(uint8_t* r, R5900Context* c, uint32_t a, __m128i v) { (this->*g_api->store128)(r, c, a, v); }
bool PS2Runtime::dispatchGuestBranch(uint8_t* r, R5900Context* c, uint32_t t, uint32_t s, uint32_t f, GuestBranchKind k, const char* n)
{ return (this->*g_api->dispatchGuestBranch)(r, c, t, s, f, k, n); }
bool PS2Runtime::eeCheckpointDue(uint32_t cycles) noexcept { return (this->*g_api->eeCheckpointDue)(cycles); }
void PS2Runtime::handleBreak(uint8_t* r, R5900Context* c) { (this->*g_api->handleBreak)(r, c); }
void PS2Runtime::handleTrap(uint8_t* r, R5900Context* c) { (this->*g_api->handleTrap)(r, c); }
void PS2Runtime::SignalException(R5900Context* c, PS2Exception e) { (this->*g_api->signalException)(c, e); }
void PS2Runtime::handleSyscall(uint8_t* r, R5900Context* c) { (this->*g_api->handleSyscall2)(r, c); }
void PS2Runtime::handleSyscall(uint8_t* r, R5900Context* c, uint32_t id) { (this->*g_api->handleSyscall3)(r, c, id); }
PS2Runtime::RecompiledFunction PS2Runtime::lookupFunction(uint32_t a) { return (this->*g_api->lookupFunction)(a); }
#ifdef _WIN32
#define PS2X_HOT_EXPORT extern "C" __declspec(dllexport)
#else
#define PS2X_HOT_EXPORT extern "C" __attribute__((visibility("default")))
#endif
#include <cstring>
void @NAME@(uint8_t*, R5900Context*, PS2Runtime*);
// The guest code this was translated from (first bytes): another overlay at the same address gets its own translation.
static const uint8_t kSignature[64] = {@SIG@};
static void PortHotGuarded(uint8_t* rdram, R5900Context* ctx, PS2Runtime* runtime) {
    if (std::memcmp(rdram + (@ADDR@u & 0x1FFFFFFu), kSignature, sizeof(kSignature)) != 0) {
        if (PS2Runtime::RecompiledFunction fresh = g_api->retranslate(runtime, @ADDR@u)) {
            fresh(rdram, ctx, runtime);
            return;
        }
    }
    @NAME@(rdram, ctx, runtime);
}
PS2X_HOT_EXPORT void ps2x_hot_bind(const PS2HotApi* api) { g_api = api; }
PS2X_HOT_EXPORT PS2Runtime::RecompiledFunction ps2x_hot_entry() { return &PortHotGuarded; }
'''


def word(ram, a):
    return struct.unpack_from('<I', ram, a & 0x1FFFFFF)[0] if (a & 0x1FFFFFF) + 4 <= RAM_SIZE else 0


def function_end(ram, start, limit=0x10000):
    """End of the function at start: after a `jr ra` + delay slot that is followed by padding or a new prologue, or
    the first undecodable/empty run. Branches beyond it are dispatched through the table."""
    a = start
    while a < start + limit:
        w = word(ram, a)
        if w == 0x03E00008:
            nxt = word(ram, a + 8)
            if nxt == 0 or (nxt >> 16) == 0x27BD:
                return a + 8
        if w == 0 and word(ram, a + 4) == 0 and word(ram, a + 8) == 0 and a > start:
            return a
        a += 4
    return a


def write_elf(path, ram, entry):
    """A minimal ELF32 MIPS executable: the whole RAM as one RWX PT_LOAD at virtual address 0."""
    ehdr = struct.pack('<16sHHIIIIIHHHHHH', b'\x7fELF\x01\x01\x01' + b'\0' * 9, 2, 8, 1, entry, 52, 0, 0, 52, 32, 1, 40, 0, 0)
    phdr = struct.pack('<8I', 1, 0x1000, 0, 0, len(ram), len(ram), 7, 0x1000)
    with open(path, 'wb') as f:
        f.write(ehdr + phdr + b'\0' * (0x1000 - 52 - 32))
        f.write(ram)


def ninja_flags(port):
    """Compile flags of the game's generated code (ps2_game_code) from build.ninja, without the precompiled header."""
    text = (port / 'build/native/build.ninja').read_text(errors='replace')
    m = re.search(r'build [^\n]*ps2_game_code\.dir[^\n]*chunk_[^\n]*\.obj:[^\n]*\n((?:  [A-Z_]+ = [^\n]*\n)+)', text)
    if not m:
        raise SystemExit('build.ninja has no ps2_game_code compile; build the game first')
    vals = dict(re.findall(r'  ([A-Z_]+) = ([^\n]*)', m.group(1)))
    flags = vals.get('FLAGS', '').split()
    flags = [f for f in flags if not f.startswith(('/Yu', '/Fp', '/FI', '-include'))]
    return flags + vals.get('DEFINES', '').split() + shlex.split(vals.get('INCLUDES', ''), posix=False)


def main():
    out, hexaddr = Path(sys.argv[1]).resolve(), sys.argv[2]
    address = int(hexaddr.split('_')[0], 16)  # tag: <address>_<hash of the guest code>
    port = out.parents[1]
    logf = out / f'hot_{hexaddr}.log'
    work = out / f'work_{hexaddr}'
    shutil.rmtree(work, ignore_errors=True)
    work.mkdir(parents=True)
    log = open(logf, 'w', encoding='utf-8', errors='replace')

    def run(cmd, cwd=None):
        log.write('> ' + ' '.join(map(str, cmd)) + '\n')
        log.flush()
        r = subprocess.run([str(c) for c in cmd], cwd=cwd, stdout=log, stderr=subprocess.STDOUT)
        if r.returncode:
            raise SystemExit(f'failed: {cmd[0]}')

    ram = (out / f'ram_{hexaddr}.bin').read_bytes()
    end = function_end(ram, address)
    write_elf(work / 'ram.elf', ram, address)
    (work / 'map.csv').write_text('Name,Start,End,Size\n' + f'hot_{hexaddr},0x{address:08X},0x{end:08X},{end - address}\n')
    (work / 'hot.toml').write_text('\n'.join([
        '[general]', 'input = "ram.elf"', 'output = "gen"', 'ghidra_output = "map.csv"', 'single_file_output = false',
        'patch_syscalls = false', 'patch_cop0 = true', 'patch_cache = true', 'stubs = []', 'skip = []']) + '\n')
    recomp = Path(os.environ.get('PS2_RECOMP_EXE') or REPO / '.local/recompiler/ps2xRecomp' /
                  ('ps2_recomp.exe' if os.name == 'nt' else 'ps2_recomp'))
    run([recomp, 'hot.toml'], cwd=work)
    sources = [p for p in (work / 'gen').glob(f'*_0x{address:x}.cpp')]
    if not sources:
        raise SystemExit('the translator produced no function')
    src = sources[0]
    name = src.stem
    text = src.read_text(encoding='utf-8', errors='surrogateescape')
    # Every call to another function goes through the runtime's table (the executable exports nothing).
    text = re.sub(r'\b(\w+)_0x([0-9a-f]+)\(rdram, ctx, runtime\)',
                  lambda m: m.group(0) if f'{m.group(1)}_0x{m.group(2)}' == name else
                  f'runtime->lookupFunction(0x{m.group(2)}u)(rdram, ctx, runtime)', text)
    if re.search(r'\bps2_(stubs|syscalls)::\w+\(', text):
        raise SystemExit('the function calls runtime handlers by name; not supported in run-time translation')
    src.write_text(text, encoding='utf-8', errors='surrogateescape')
    sig = ram[address & 0x1FFFFFF:(address & 0x1FFFFFF) + 64]
    (work / 'shim.cpp').write_text(SHIM.replace('@NAME@', name).replace('@ADDR@', f'0x{address:x}')
                                   .replace('@SIG@', ', '.join(str(b) for b in sig)))
    flags = ninja_flags(port)
    dll = out / (f'hot_{hexaddr}.dll' if os.name == 'nt' else f'hot_{hexaddr}.so')
    if os.name == 'nt' and not os.environ.get('CC'):   # MSVC; llvm-mingw (CC=clang) takes the branch below
        run(['cl', '/nologo', '/LD', '/I', work / 'gen'] + flags + [src, work / 'shim.cpp', '/Fe:' + str(dll),
             '/Fo:' + str(work) + os.sep, '/link', '/NOIMPLIB', '/NOEXP'], cwd=work)
    else:
        run([os.environ.get('CXX', 'c++'), '-shared'] + ([] if os.name == 'nt' else ['-fPIC']) + ['-I', work / 'gen'] + flags +
            [src, work / 'shim.cpp', '-o', dll], cwd=work)
    log.write(f'ok {dll}\n')
    log.close()
    shutil.rmtree(work, ignore_errors=True)


if __name__ == '__main__':
    main()
